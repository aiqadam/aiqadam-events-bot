import { createRequire } from 'node:module';
import { createHash, createHmac } from 'node:crypto';
import { load, suite } from './_load.mjs';
globalThis.require = createRequire(import.meta.url);
const { code } = await load('id-migrate-verify');
const t = suite();
// Выдуманные ключ и люди (тестовый диапазон).
const MK = 'm'.repeat(40), URL_ = 'https://flow.example.test/api/v1/webhooks/abc123/sync';
const mac = (id) => createHmac('sha256', MK).update(id, 'utf8').digest('hex');
const A = '9000000000000001', B = '9000000000000002', C = '9000000000000003';
const res1 = { ok: true, sent: 2, skipped: 0, macs: [mac(B), mac(A)], counts: { members_inserted: 2, members_existing: 0, skipped_deleted: 0, skipped_bad: 0, created: { base: 2, module: 2, mailing: 1 }, existing: {} } };
const res2 = { ok: true, sent: 1, skipped: 1, macs: [], counts: { members_inserted: 0, skipped_deleted: 1, created: {}, existing: {} } };
let calls = [];
const answer = (...seq) => { calls = []; let i = 0; globalThis.fetch = async (url, init) => { calls.push(JSON.parse(init.body)); const a = seq[Math.min(i++, seq.length - 1)]; if (a === 'net') throw new Error('net'); return { status: a[0], json: async () => a[1] }; }; };
const go = (o = {}) => code({ migration_key: MK, url: URL_, mode: 'test', run: 'r1', results: [res1, res2], expected: { sent: 3 }, no_wait: true, ...o });

answer([200, { ok: true, match: true, digest_ok: true, count_ok: true, marked: 2 }]);
let r = await go();
const p = JSON.parse(calls[0].payload);
t.ok(p.kind === 'verify' && p.sent === 3 && p.skipped === 1, 'sums sent and skipped');
t.ok(p.digest === createHash('sha256').update([mac(A), mac(B)].sort().join('\n'), 'utf8').digest('hex'), 'digest = sha256 of sorted macs (ID canon)');
t.ok(r.pass && r.sent_ok && r.accounted_ok && r.match && r.totals.created.base === 2 && r.totals.created.mailing === 1, 'pass');
t.ok(!JSON.stringify(r).includes(mac(A)) && !JSON.stringify(r).includes(A), 'no mac and no id in the output');
answer([200, { ok: true, match: false, digest_ok: false, count_ok: true }]);
r = await go();
t.ok(!r.pass && !r.match, 'ID says no match → fail');
answer([200, { ok: true, match: true }]);
r = await go({ expected: { sent: 4 } });
t.ok(!r.pass && !r.sent_ok, 'sent differs from expected → fail');
r = await go({ results: [{ ...res1, counts: { ...res1.counts, members_inserted: 1 } }, res2] });
t.ok(!r.pass && !r.accounted_ok, 'not every sent person accounted → fail');
answer('net', [200, { ok: true, match: true }]);
r = await go();
t.ok(r.pass && calls.length === 2 && calls[0].request_id !== calls[1].request_id, 'retry with a fresh request_id');
answer([403, { ok: false, reason: 'closed' }]);
await t.throws(() => go(), /verify_failed: 403 closed/, 'closed window stops');
await t.throws(() => go({ results: [res1, null] }), /bad_results/, 'a failed batch in results');
await t.throws(() => go({ results: [{ ...res1, macs: ['x'] }] }), /bad_results/, 'malformed mac');
await t.throws(() => go({ mode: 'dry-real' }), /bad_mode/, 'dry mode never verifies');
t.done('id-migrate-verify');
