import { load, suite } from './_load.mjs';
const { code } = await load('id-call-result');
const t = suite();
// Формы выхода send_request сняты на QA (W146); люди выдуманные.
const A = '9000000000000951';
const go = (out, sign_reason = 'ok') => code({ sign_reason, out });
const same = (r, ok, status, reason) => r.ok === ok && r.status === status && r.reason === reason;

let r = await go({ status: 200, headers: { 'content-type': 'application/json' }, body: { ok: true, found: true, profile: { telegram_id: A }, mailing: false } });
t.ok(same(r, true, 200, 'ok') && r.body.profile.telegram_id === A && r.body.mailing === false, '2xx ok:true → ok, body passed through');
r = await go({ status: 200, headers: {}, body: { ok: true, found: false, profile: {} } });
t.ok(same(r, true, 200, 'ok') && r.body.found === false, '2xx found:false is still ok');
r = await go({ status: 200, headers: {}, body: { found: true } });
t.ok(same(r, false, 200, 'http_200'), '2xx without ok:true → not ok, status kept');
r = await go({ status: 200, headers: {}, body: { ok: 'true' } });
t.ok(same(r, false, 200, 'http_200'), 'ok must be boolean true');
r = await go({ status: 200, headers: {}, body: '<html>' });
t.ok(same(r, false, 0, 'no_json') && JSON.stringify(r.body) === '{}', '2xx non-JSON → status 0');
r = await go({ status: 200, headers: {}, body: [1] });
t.ok(same(r, false, 0, 'no_json'), '2xx array body → status 0');
r = await go({ status: 200, headers: {}, body: { ok: true, response: { status: 401 } } });
t.ok(same(r, true, 200, 'ok'), 'a 2xx body key named response does not switch shape');

r = await go({ response: { status: 401, body: { ok: false, reason: 'bad_signature' } } });
t.ok(same(r, false, 401, 'http_401') && r.body.reason === 'bad_signature', '401 → status and body for the caller');
r = await go({ response: { status: 409, body: { ok: false, reason: 'base_required' } } });
t.ok(same(r, false, 409, 'http_409') && r.body.reason === 'base_required', '409 consent reason passed');
r = await go({ response: { status: 403, body: { ok: false, reason: 'no_consent' } } });
t.ok(same(r, false, 403, 'http_403'), '403 no_consent');
r = await go({ response: { status: 400, body: { ok: false, reason: 'bad_request' } } });
t.ok(same(r, false, 400, 'http_400'), '400');
r = await go({ response: { status: 502, body: { ok: false } } });
t.ok(same(r, false, 502, 'http_502'), '5xx with JSON keeps status');
r = await go({ response: { status: 500 } });
t.ok(same(r, false, 0, 'no_json'), 'timeout shape (500, no body) → status 0');
r = await go({ response: { status: 403, body: 'Forbidden' } });
t.ok(same(r, false, 0, 'no_json'), 'platform block (string body) → status 0');
r = await go({ response: { body: { ok: true } } });
t.ok(same(r, false, 0, 'network'), 'no status → network');
r = await go({ response: { status: 1000, body: { ok: true } } });
t.ok(same(r, false, 0, 'network'), 'status out of range → network');
r = await go({ status: '200', headers: {}, body: { ok: true } });
t.ok(same(r, false, 0, 'network'), 'string status is not trusted');

r = await go('', 'ok');
t.ok(same(r, false, 0, 'network'), 'failed step (output not an object) → network');
r = await go(undefined, 'ok');
t.ok(same(r, false, 0, 'network'), 'missing output → network');
r = await go({ status: 200, headers: {}, body: { ok: true } }, 'bad_api');
t.ok(same(r, false, 0, 'bad_api'), 'sign refusal wins over any output');
r = await go('', 'not_configured');
t.ok(same(r, false, 0, 'not_configured'), 'not_configured');
r = await go('', 'bad_body');
t.ok(same(r, false, 0, 'bad_body'), 'bad_body');
r = await go('', null);
t.ok(same(r, false, 0, 'not_configured'), 'missing sign reason → not_configured');
r = await go('', 'Ошибка с данными 9000000000000951');
t.ok(same(r, false, 0, 'not_configured'), 'odd sign reason is not echoed into the log');
t.done('id-call-result');
