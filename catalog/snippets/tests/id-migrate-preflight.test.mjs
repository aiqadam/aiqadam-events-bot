import { load, suite } from './_load.mjs';
const { code } = await load('id-migrate-preflight');
const t = suite();
// Только выдуманные люди: тестовый диапазон 9xxxxxxxxxxxxxxx; REAL — выдуманный короткий id.
const NOW = Date.parse('2026-11-24T12:00:00Z'), OPEN = '2026-11-24T14:00:00Z';
const rec = (o) => ({ id: 'r', cells: Object.fromEntries(Object.entries(o).map(([k, v], i) => ['f' + i, { fieldName: k, value: v }])) });
const U = (id, o = {}) => rec({ telegram_id: id, first_name: 'Test', consent_pdn: 'true', consent_pdn_at: '2026-10-01T10:00:00.000Z', consent_marketing: null, blocked_bot: 'false', phone: '+000', ...o });
const ids = (n) => Array.from({ length: n }, (_, i) => String(9000000000000001 + i));
const T = (rows, o = {}) => code({ mode: 'test', run: 'r1', open_until: OPEN, now_ms: NOW, users_all: [], users_true: [],
  test_all: rows, test_true: rows.filter((r) => Object.values(r.cells).some((c) => c.fieldName === 'consent_pdn' && c.value === 'true')), ...o });

let r = await T(ids(23).map((i) => U(i)));
t.ok(r.ok && r.send && r.batch_count === 3 && r.batches[0].length === 10 && r.batches[2].length === 3, '23 people → 10/10/3');
t.ok(!('phone' in r.batches[0][0]) && r.batches[0][0].last_name === null, 'phone not carried, missing → null');
t.ok(r.expected.sent === 23 && r.expected.mailing === 0 && r.counts.hist.blocked_bot.false === 23, 'expected numbers and histogram');
r = await T([U(ids(1)[0]), U(ids(2)[1], { consent_pdn: 'false' }), U(ids(3)[2], { consent_pdn: null })]);
t.ok(r.ok && r.expected.sent === 1 && r.counts.left_behind === 2, 'no base consent → left behind');
r = await T([U(ids(1)[0], { consent_marketing: 'true', consent_marketing_at: '2026-10-02T00:00:00Z' })]);
t.ok(r.expected.mailing === 1, 'mailing counted');
r = await T([U(ids(1)[0], { consent_marketing: 'true', consent_marketing_at: null })]);
t.ok(!r.ok && r.reason.includes('mkt_true_no_date') && r.batches.length === 0, 'marketing without a date stops');
r = await T([U(ids(1)[0], { consent_pdn_at: '' })]);
t.ok(!r.ok && r.reason.includes('pdn_true_no_date'), 'base without a date stops');
r = await T([U(ids(1)[0], { blocked_bot: 'yes' })]);
t.ok(!r.ok && r.reason.includes('bad_value') && r.counts.hist.blocked_bot.other === 1, 'odd dropdown value stops');
r = await T([U(ids(1)[0]), U(ids(1)[0])]);
t.ok(r.ok && r.counts.merged_dupes === 1 && r.expected.sent === 1, 'agreeing duplicate merged');
r = await T([U(ids(1)[0]), U(ids(1)[0], { first_name: 'Other' })]);
t.ok(!r.ok && r.reason.includes('disagreeing_dupes'), 'disagreeing duplicate stops');
r = await T([U('1234567')]);
t.ok(!r.ok && r.reason.includes('wrong_range'), 'real id in a test run stops');
r = await code({ mode: 'real', run: 'r1', open_until: OPEN, now_ms: NOW, users_all: [U(ids(1)[0])], users_true: [U(ids(1)[0])], test_all: [], test_true: [] });
t.ok(!r.ok && r.reason.includes('wrong_range'), 'test id in a real run stops');
r = await T([U('0123')]);
t.ok(!r.ok && r.reason.includes('bad_id'), 'bad id stops');
r = await T([U(ids(1)[0], { city: 'x'.repeat(257) })]);
t.ok(!r.ok && r.reason.includes('too_long'), 'too long stops');
r = await T([U(ids(1)[0])], { test_true: [] });
t.ok(!r.ok && r.reason.includes('read_mismatch'), 'reads disagree → stop');
r = await T([U(ids(1)[0])], { open_until: '2026-11-24T11:00:00Z' });
t.ok(!r.ok && r.reason === 'closed', 'closed window, sending mode');
r = await T([U(ids(1)[0])], { mode: 'dry-test', open_until: '' });
t.ok(r.ok && !r.send && r.expected.sent === 1, 'dry run needs no window and sends nothing');
r = await code({ mode: 'dry-real', run: 'r1', users_all: [U('1234567')], users_true: [U('1234567')], test_all: null, test_true: null });
t.ok(r.ok && !r.send && r.expected.sent === 1, 'dry-real reads users only');
t.ok((await T([], { mode: 'off' })).reason === 'bad_mode', 'off → bad_mode');
t.ok((await T([], { run: '{{variables.x}}' })).reason === 'bad_run', 'unset run');
r = await T([]);
t.ok(r.ok && !r.send && r.batch_count === 0, 'empty source sends nothing');
await t.throws(() => T([], { test_all: null }), /read_failed/, 'failed read fails the run');
t.done('id-migrate-preflight');
